// 고객이 적은 개인정보를 외부 AI로 보내거나 통계에 남기기 전에 가린다.
// 셀프가이드 AI 질문(api/ai-query)·AI 답변 피드백·상담 도우미(liveChatAssist)가 같이 쓴다.
// 오탐을 줄이려고 형식이 분명한 것만 가린다 — 이름처럼 형식이 없는 정보는 가리지 못한다.

const PATTERNS: Array<[RegExp, string]> = [
  [/[\w.+-]+@[\w-]+\.[\w.-]+/g, "[이메일]"],
  // 주민등록번호 (뒷자리 첫 숫자 1~4)
  [/\b\d{6}\s*-\s*[1-4]\d{6}\b/g, "[주민번호]"],
  // 카드번호 16자리(4자리씩, 구분자 있거나 없거나)
  [/\b(?:\d{4}[-\s]?){3}\d{4}\b/g, "[카드번호]"],
  // 휴대폰·일반 전화
  [/\b01[016789][-\s.]?\d{3,4}[-\s.]?\d{4}\b/g, "[전화번호]"],
  [/\b0\d{1,2}[-\s.]\d{3,4}[-\s.]\d{4}\b/g, "[전화번호]"],
  // 자사몰 주문번호(YYYYMMDD-NNNNNNN)
  [/\b20\d{6}-\d{7}\b/g, "[주문번호]"],
  // 주소 — '○○구/군' 뒤 도로명·동 번지까지 있는 경우와 '○동 ○호'만 가린다("세탁기로 2번" 같은 오탐 방지)
  [/(?:[가-힣]+(?:특별시|광역시|특별자치시|도|시)\s+)?[가-힣]+(?:구|군)\s+[가-힣0-9]+(?:로|길|동|읍|면)\s*\d+(?:-\d+)?(?:\s*번길\s*\d+)?/g, "[주소]"],
  [/\d{1,4}\s*동\s*\d{1,4}\s*호/g, "[주소]"],
];

export function maskPersonalInfo(text: string) {
  return PATTERNS.reduce((acc, [pattern, label]) => acc.replace(pattern, label), text);
}
